#!/usr/bin/env python3
"""
build-icons.py — pack the SVGs in your "icon" folder into icons-data.js.

Why: browsers refuse to load files from a folder when index.html is opened by
double-clicking it. icons-data.js carries the same SVGs inside a script file,
so the widget works that way too (and on GitHub Pages, if the icon folder is
ever left out). When the page IS served over http(s), the widget reads the
live files in the icon folder first, so edits there show up without rebuilding.

Usage (from the weatherwidget folder):
    python3 build-icons.py            # uses ./icon (or ./icons)
    python3 build-icons.py path/to/folder

Re-run it whenever you add or change an icon.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

# What the widget looks for (base names, in the order it tries them).
EXPECTED = {
    "clear-day": ["clear-day"],
    "clear-night": ["clear-night"],
    "partly-cloudy-day": ["partly-cloudy-day"],
    "partly-cloudy-night": ["partly-cloudy-night"],
    "cloudy": ["cloudy"],
    "fog": ["foggy-day"],   # optional: the cloudy icon is used if absent
    "drizzle": ["drizzle"],
    "rain": ["rain", "heavy-rain"],
    "thunder-storm": ["thunder-storm", "thunderstorm"],
    "snow": ["snow"],
    "hail": ["hail"],
    "wind": ["wind"],
    "sunrise": ["sunrise"],
    "sunset": ["sunset"],
    "hot": ["hot"],
    "cold": ["cold"],
}


def find_folder():
    if len(sys.argv) > 1:
        p = Path(sys.argv[1]).expanduser()
        return p if p.is_dir() else None
    for name in ("icon", "icons"):
        if (HERE / name).is_dir():
            return HERE / name
    return None


def main():
    folder = find_folder()
    if folder is None:
        print('Could not find an "icon" folder next to build-icons.py.')
        print("Create one and put your .svg files in it (or pass the folder path).")
        return 1

    files = sorted(folder.glob("*.svg"))
    if not files:
        print(f"No .svg files found in {folder}")
        return 1

    data = {}
    for f in files:
        data[f.name] = f.read_text(encoding="utf-8-sig")

    out = HERE / "icons-data.js"
    out.write_text(
        "// Generated by build-icons.py from the icon folder — re-run it after changing icons.\n"
        "window.WEATHER_ICON_DATA = "
        + json.dumps(data, ensure_ascii=False, indent=0)
        + ";\n",
        encoding="utf-8",
    )
    print(f"Packed {len(files)} icons from {folder.name}/ into {out.name}\n")

    # Report what's there and what isn't.
    names = set(data)
    missing_any = False
    for key, bases in EXPECTED.items():
        has_fill = any(f"{b}_default.svg" in names for b in bases)
        has_outline = any(f"{b}_outline.svg" in names for b in bases)
        shared = any(f"{b}.svg" in names for b in bases)
        if shared:
            status = "ok (one file, used for Fill and Outline)"
        elif has_fill and has_outline:
            status = "ok (Fill + Outline)"
        elif has_fill:
            status = "Fill only - no *_outline.svg"
            missing_any = True
        elif has_outline:
            status = "Outline only - no *_default.svg"
            missing_any = True
        else:
            status = "MISSING" + (" (cloudy icon is used instead)" if key == "fog" else "")
            missing_any = True
        print(f"  {key:<22} {status}")

    if missing_any:
        print("\nAnything marked Fill only / Outline only / MISSING falls back as noted above.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
